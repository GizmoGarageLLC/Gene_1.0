"""Keeps docs/BOM.md section 5 and docs/BOM.csv in step with the checks.

1. The cable table in BOM.md section 5 is rebuilt from route.py's results for all four setups (cables.json,
   cables_pb.json, cables_am.json, cables_pb_am.json). A run that comes out the same in several setups is one row;
   where it differs (or exists only in some setups) each version gets its own row with the setups it applies to.
2. BOM.csv is written from every table in BOM.md sections 1-5 (category = the section), so the two never drift apart.

Run after route.py for all four setups:  python bom_tables.py
"""
import json, os, re, csv, io

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
MD = os.path.join(ROOT, "docs", "BOM.md")
SETUPS = [("", "pack + LCD"), ("_pb", "power bank + LCD"), ("_am", "pack + AMOLED"), ("_pb_am", "power bank + AMOLED")]

# ---- 1. cable table ----
rows = {}          # (name, dia, length, buy, gap) -> [setup labels]
order = []
for suf, label in SETUPS:
    for c in json.load(open(os.path.join(HERE, f"cables{suf}.json"), encoding="utf-8"))["cables"]:
        assert c["ok"], f"{c['name']} not routed in {label}"
        k = (c["name"], c["dia"], c["length"], c["buy"], c["exact_gap"])
        if k not in rows: rows[k] = []; order.append(k)
        rows[k].append(label)


def used_in(labels):
    if len(labels) == 4: return "all"
    if set(labels) == {"pack + LCD", "pack + AMOLED"}: return "pack"
    if set(labels) == {"power bank + LCD", "power bank + AMOLED"}: return "power bank"
    if set(labels) == {"pack + LCD", "power bank + LCD"}: return "LCD eyes"
    if set(labels) == {"pack + AMOLED", "power bank + AMOLED"}: return "AMOLED eyes"
    return ", ".join(labels)


n = {label: sum(label in v for v in rows.values()) for _, label in SETUPS}
lines = ["| Cable | Setups | Envelope dia | Route mm | Buy mm | Tightest gap mm |", "|---|---|---|---|---|---|"]
for k in order:
    name, dia, length, buy, gap = k
    lines.append(f"| {name} | {used_in(rows[k])} | {dia:g} | {length} | **{buy}** | {gap:.2f} |")
lines.append("| GPIO ribbon, Pi to crown (female-to-male) | all | flat, 51 wide | ~110 | **200** | 0.3 |")
table = "\n".join(lines)
intro = ("Every run was routed through the free space in the head and checked as a solid tube against every part and every "
         f"other cable, in all four setups (pack + LCD {n['pack + LCD']} runs, power bank + LCD {n['power bank + LCD']}, "
         f"pack + AMOLED {n['pack + AMOLED']}, power bank + AMOLED {n['power bank + AMOLED']}; all clear). \"Buy\" is the route "
         "plus 15 % for bends and 30 mm at the connectors, rounded up to a stock length. A run that differs between setups "
         "has a row per version. Generated by `cad/tools/bom_tables.py` from `route.py`'s results.")
outro = ("Ribbons and leads were checked with a 4 mm envelope (3 mm for the DYNAMIXEL and servo-power leads, 2.5 mm for "
         "the speaker wires, 6 mm for the pack leads and slip-ring bundle). The LCD and AMOLED eye leads, and the Pi power "
         "leads into the Pi, run their last few millimetres into the Pi mock, which is a solid block, ports included.")

s = open(MD, encoding="utf-8", newline="").read()
nl = "\r\n" if "\r\n" in s else "\n"
a = s.index("## 5. Cables"); b = s.index("## 6.")
sec = s[a:b].replace("\r\n", "\n")
head = sec.split("\n\n")[0] + "\n\n"
wiring = [p for p in sec.split("\n\n") if "WIRING.md" in p]
new = head + (wiring[0] + "\n\n" if wiring and wiring[0] not in head else "") + intro + "\n\n" + table + "\n\n" + outro + "\n\n"
s = s[:a] + new.replace("\n", nl) + s[b:]
open(MD, "w", encoding="utf-8", newline="").write(s)
print(f"BOM.md section 5: {len(order)} cable rows")

# ---- 2. BOM.csv from the BOM.md tables ----
def cells(line):
    return [re.sub(r"\*\*|`", "", c).strip() for c in line.strip().strip("|").split("|")]


out = io.StringIO(); w = csv.writer(out, lineterminator="\n")
w.writerow(["Category", "Item", "Qty", "Notes", "Other"])
cat = None; header = None; count = 0
for line in s.replace("\r\n", "\n").split("\n"):
    m = re.match(r"#{2,3} (\d+b?)\. (.+)", line)
    if m:
        cat = m.group(2).strip(); header = None
        if m.group(1).startswith("6"): cat = None
        continue
    if not cat or not line.startswith("|"): header = None if not line.startswith("|") else header; continue
    c = cells(line)
    if header is None: header = c; continue
    if set("".join(c)) <= set("-: "): continue
    h = [x.lower() for x in header]
    if h[0] == "file":                       # the plates table
        w.writerow([cat + " (plates)", c[0], "1", "; ".join(f"{header[i]}: {c[i]}" for i in range(1, len(c))), ""]); count += 1
    elif h[0] == "cable":
        w.writerow(["Cable", c[0], "1", f"Setups {c[1]}; envelope {c[2]} mm; route {c[3]} mm; gap {c[5]} mm", f"Buy {c[4]} mm"]); count += 1
    else:
        qty = c[1] if len(c) > 1 else ""
        notes = c[2] if len(c) > 2 else ""
        other = "; ".join(f"{header[i]}: {c[i]}" for i in range(3, len(c)))
        w.writerow([cat, c[0], qty, notes, other]); count += 1
open(os.path.join(ROOT, "docs", "BOM.csv"), "w", encoding="utf-8", newline="").write(out.getvalue())
print(f"BOM.csv: {count} rows")
